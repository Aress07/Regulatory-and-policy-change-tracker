import streamlit as st
from shared import AI_BADGE, SYNTHETIC_BADGE, impact_badge, load_change_detail, load_changes

changes = load_changes()
if changes.empty:
    st.info("No changes detected yet.", icon=":material/info:")
    st.stop()

labels = {
    r.change_id: f"{r.instrument} · {r.section_key} · {r.change_type} · {r.to_date:%Y-%m-%d}"
    for r in changes.itertuples()
}
ids = list(labels)
current = st.session_state.get("selected_change")
change_id = st.selectbox(
    "Change", ids, index=ids.index(current) if current in labels else 0, format_func=labels.get
)
st.session_state.selected_change = change_id
c = load_change_detail(change_id)
if c is None:
    st.error("This change no longer exists. Pick another one.", icon=":material/error:")
    st.stop()

heading = f" · {c['heading']}" if c["heading"] else ""
st.subheader(f"{c['instrument']} · {c['section_key']}{heading}")
badges = [f":gray-badge[{c['change_type']}]", impact_badge(c["impact"])]
if c["is_synthetic"]:
    badges.append(SYNTHETIC_BADGE)
st.markdown(" ".join(badges))
st.caption(
    f"From {c['from_version']} to {c['to_version']}"
    + (f" · word similarity {c['similarity']:.2f}" if c["similarity"] is not None else "")
)
st.link_button(
    "Official consolidated text on EUR-Lex", c["source_url"], icon=":material/open_in_new:"
)

with st.container(border=True):
    st.markdown(f"**What changed** {AI_BADGE}")
    if c["summary"]:
        st.write(c["summary"])
        st.markdown(f"**Impact:** {impact_badge(c['impact'])}  \n{c['impact_rationale']}")
        st.markdown(
            "**Topics:** "
            + ", ".join(c["topics"] or [])
            + "  \n**Sectors:** "
            + ", ".join(c["sectors"] or [])
        )
        with st.expander("How was this generated?", icon=":material/help:"):
            st.markdown(
                "- The change itself was found by a deterministic text diff, not by AI.\n"
                f"- The explanation above was written by `{c['enrichment_model']}` with prompt "
                f"`{c['prompt_version']}` on {c['enriched_at']:%Y-%m-%d}, "
                "from the old and new text only.\n"
                "- It can be wrong or incomplete. The official text is authoritative."
            )
    elif c["enrichment_failed"]:
        st.warning("The AI explanation failed validation for this change; see the diff below.")
    else:
        st.caption("No AI explanation yet. The diff below is complete.")

st.markdown(
    "**Text comparison** (deterministic; removed words struck through, added words highlighted)"
)
if c["diff_html"]:
    # diff_html is generated by regtracker.diff with all source text HTML-escaped.
    st.html(
        "<style>del{background:#ffd7d5;text-decoration:line-through}ins{background:#d1f5d3;"
        "text-decoration:none}.diff{white-space:pre-wrap;line-height:1.6}</style>"
        f"<div class='diff'>{c['diff_html']}</div>"
    )
left, right = st.columns(2, border=True)
with left:
    st.markdown("**Before**")
    st.text(c["old_text"] or "(not present in the earlier version)")
with right:
    st.markdown("**After**")
    st.text(c["new_text"] or "(removed in the later version)")
