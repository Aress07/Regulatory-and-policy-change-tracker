"""RSS 2.0 feed of the newest medium- and high-impact real changes."""

import xml.etree.ElementTree as ET
from datetime import UTC, datetime
from email.utils import format_datetime

import duckdb

from regtracker.app.queries import changes

FEED_TITLE = "EU Regulation Change Tracker: notable changes"
DISCLAIMER = "Not legal advice. Summaries are AI-generated; check the official text."


def build_feed(
    con: duckdb.DuckDBPyConnection,
    site_url: str,
    limit: int = 50,
    now: datetime | None = None,
) -> bytes:
    frame = changes(con)
    notable = frame[frame["impact"].isin(["medium", "high"]) & ~frame["is_synthetic"]].head(limit)

    rss = ET.Element("rss", version="2.0")
    channel = ET.SubElement(rss, "channel")
    ET.SubElement(channel, "title").text = FEED_TITLE
    ET.SubElement(channel, "link").text = site_url
    ET.SubElement(channel, "description").text = (
        "Medium- and high-impact changes detected in EU digital regulation. " + DISCLAIMER
    )
    ET.SubElement(channel, "language").text = "en"
    ET.SubElement(channel, "lastBuildDate").text = format_datetime(now or datetime.now(UTC))

    for row in notable.itertuples():
        item = ET.SubElement(channel, "item")
        heading = f" ({row.heading})" if row.heading else ""
        ET.SubElement(
            item, "title"
        ).text = f"[{row.impact}] {row.instrument} {row.section_key}{heading}: {row.change_type}"
        ET.SubElement(item, "link").text = row.source_url
        ET.SubElement(item, "description").text = (
            f"{row.summary} Impact: {row.impact} - {row.impact_rationale} "
            f"(AI-generated by {row.enrichment_model}, prompt {row.prompt_version}.) {DISCLAIMER}"
        )
        ET.SubElement(item, "guid", isPermaLink="false").text = row.change_id
        published = datetime.combine(row.to_date, datetime.min.time(), tzinfo=UTC)
        ET.SubElement(item, "pubDate").text = format_datetime(published)
        for topic in row.topics or []:
            ET.SubElement(item, "category").text = topic

    ET.indent(rss)
    data: bytes = ET.tostring(rss, encoding="utf-8", xml_declaration=True)
    return data


def validate_feed(data: bytes) -> list[str]:
    """Structural RSS 2.0 checks (required channel and item elements). Empty list = valid."""
    problems: list[str] = []
    root = ET.fromstring(data)
    if root.tag != "rss" or root.get("version") != "2.0":
        problems.append("root must be <rss version='2.0'>")
    channel = root.find("channel")
    if channel is None:
        return [*problems, "missing <channel>"]
    for tag in ("title", "link", "description"):
        if not (channel.findtext(tag) or "").strip():
            problems.append(f"channel missing <{tag}>")
    for i, item in enumerate(channel.findall("item")):
        if not (item.findtext("title") or item.findtext("description")):
            problems.append(f"item {i} needs <title> or <description>")
        guid = item.find("guid")
        if guid is None or not (guid.text or "").strip():
            problems.append(f"item {i} missing <guid>")
    return problems
